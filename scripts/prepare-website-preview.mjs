import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const args = process.argv.slice(2);
const index = args.indexOf('--installer');
if (index < 0 || !path.isAbsolute(args[index + 1] ?? '')) throw new Error('Pass the preserved preview installer as an absolute --installer path');
const manifest = JSON.parse(await fs.readFile('docs/desktop/evidence/windows-build-manifest.json', 'utf8'));
const expected = manifest.artifacts.find(a => a.name.endsWith('.exe'));
assert.equal(manifest.build.commit, '490da683ea29ea984055d3487e0c0ba0e3fc6375');
const bytes = await fs.readFile(args[index + 1]);
const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
assert.equal(bytes.length, expected.size, 'Preserved preview size mismatch');
assert.equal(sha256, expected.sha256, 'Preserved preview hash mismatch');
const dir = path.resolve('release/website-preview');
await fs.mkdir(dir, { recursive: true });
await fs.writeFile(path.join(dir, expected.name), bytes);
const website = { schema: 1, product: 'Meldiq Desktop', platform: 'windows', architecture: 'x64', version: manifest.build.version, channel: 'internal-preview', label: 'Unsigned development preview — internal testing', sourceCommit: manifest.build.commit, artifact: { filename: expected.name, bytes: bytes.length, sha256 }, signed: false, automaticUpdates: false, systemRequirements: 'Provisional; physical Windows hardware benchmarks pending', publicReleaseApproved: false, published: false, downloadUrl: null, websitePage: 'https://meldiq.app/download', websiteIntegrationStatus: 'Prepared metadata only; existing public website still lists Windows as coming soon', acceptance: 'Not production ready; see docs/desktop/PRODUCTION_READINESS_CHECKLIST.md' };
await fs.writeFile(path.join(dir, 'windows-preview.json'), JSON.stringify(website, null, 2) + '\n');
await fs.writeFile(path.join(dir, 'checksums.sha256'), `${sha256}  ${expected.name}\n`);
console.log(JSON.stringify({ stagedDirectory: dir, sha256, signed: false, published: false, publicReleaseApproved: false }));
