import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const { extractFile } = createRequire(import.meta.url)('@electron/asar');
const filename = process.argv[2];
const read = p => extractFile(filename, path.normalize(p)).toString('utf8');
const build = JSON.parse(read('dist/build-info.json'));
const config = JSON.parse(read('dist/runtime-config.json'));
const key = JSON.parse(fs.readFileSync('config/update-key.json', 'utf8'));
assert.equal(build.distribution, 'private-direct');
assert.equal(build.updateLab, false);
assert.equal(config.privateUpdatesEnabled, true);
assert.equal(config.updateOrigin, 'https://meldiq.app/desktop-updates');
assert.equal(config.updateKeys.length, 1);
assert.equal(config.updateKeys[0].keyId, key.keyId);
assert.equal(crypto.createHash('sha256').update(crypto.createPublicKey(config.updateKeys[0].publicKey).export({ type: 'spki', format: 'der' })).digest('hex'), key.keyId);
const main = read('dist/main/main.cjs');
assert(!main.includes('MELDIQ_UPDATE_LAB_CONTROL') && !main.includes('meldiq-update-qualification'), 'Public installer must not contain lab controls');
console.log(JSON.stringify({ version: build.version, commit: build.commit, privateUpdatesEnabled: true, keyId: key.keyId, labHooksAbsent: true, scope: 'Actual installed public candidate ASAR' }));
